import { mkRoom, watch } from './harness.ts';
import type { Heightfield } from '../../../shared/heightfield.ts';
const H = (v: number): Heightfield => ({ size: 4, data: new Uint8Array(16).fill(v), stride: 1 });
const room = mkRoom({ mode: 'ctf', bases: { alpha: { x: -70, y: 0, z: 0 }, bravo: { x: 70, y: 0, z: 0 } } }, 'ctf', 7, false, H(60));
const orig = (room as any).pushStructureUpdate;
let called = 0;
(room as any).pushStructureUpdate = (s: string) => { called++; console.log('push called, before-len', s.length); return orig.call(room, s); };
const w = watch(room);
room.field = H(120);
room.refreshFlagHomes();
console.log('called:', called, 'msgs:', w.msgs.length);
process.exit(0);
